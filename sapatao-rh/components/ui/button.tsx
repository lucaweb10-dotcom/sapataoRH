function Button({
  className,
  variant = "default",
  size = "default",
  nativeButton,
  render,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  // O Base UI assume um <button> nativo no `render` e reclama no dev quando
  // trocamos por <a>/<Link>. Deduzimos aqui para nao repetir em cada chamada.
  const isNativeButton =
    nativeButton ??
    (isValidElement(render) ? render.type === "button" : true)

  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      nativeButton={isNativeButton}
      render={render}
      {...props}
    />
  )
}

export { Button, buttonVariants }
